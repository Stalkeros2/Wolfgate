using System;
using System.Collections.Generic;
using Content.Shared.IdentityManagement;
using Content.Shared._WF.Intimacy;
using Content.Shared._WF.Intimacy.Events;
using Content.Shared._WF.Intimacy.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Prototypes;

namespace Content.Client._WF.Intimacy.UI;

/// <summary>The interaction window: every act, the reason it cannot run, and the pace to run it at.</summary>
[GenerateTypedNameReferences]
public sealed partial class WFInteractionWindow : DefaultWindow
{
    private static readonly WFIntimacyIntensity[] Intensities =
    {
        WFIntimacyIntensity.VeryGentle,
        WFIntimacyIntensity.Gentle,
        WFIntimacyIntensity.Normal,
        WFIntimacyIntensity.Hard,
        WFIntimacyIntensity.Rough,
    };

    private static readonly WFIntimacySpeed[] Speeds =
    {
        WFIntimacySpeed.Slow,
        WFIntimacySpeed.Normal,
        WFIntimacySpeed.Fast,
    };

    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _ent = default!;

    public event Action<ProtoId<IntimacyActPrototype>, WFIntimacyIntensity, WFIntimacySpeed>? OnStart;
    public event Action? OnRefresh;
    public event Action? OnStop;

    /// <summary>The body this menu is aimed at.</summary>
    public NetEntity Target { get; private set; }

    private WFIntimacyIntensity _intensity = WFIntimacyIntensity.Normal;
    private WFIntimacySpeed _speed = WFIntimacySpeed.Normal;

    public WFInteractionWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        foreach (var intensity in Intensities)
            IntensityButton.AddItem(IntensityName(intensity));

        foreach (var speed in Speeds)
            SpeedButton.AddItem(SpeedName(speed));

        IntensityButton.SelectId(Array.IndexOf(Intensities, WFIntimacyIntensity.Normal));
        SpeedButton.SelectId(Array.IndexOf(Speeds, WFIntimacySpeed.Normal));

        IntensityButton.OnItemSelected += args =>
        {
            IntensityButton.SelectId(args.Id);
            _intensity = Intensities[args.Id];
        };

        SpeedButton.OnItemSelected += args =>
        {
            SpeedButton.SelectId(args.Id);
            _speed = Speeds[args.Id];
        };

        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        StopButton.OnPressed += _ => OnStop?.Invoke();
    }

    /// <summary>Renders one menu: the target, why the whole window is useless, then a row per act.</summary>
    public void Apply(WFIntimacyMenuEvent menu)
    {
        Target = menu.Target;

        var target = _ent.GetEntity(menu.Target);
        TargetLabel.Text = Loc.GetString("wf-intimacy-window-target", ("target", Identity.Name(target, _ent)));

        var reasons = new List<string>();
        if ((menu.Flags & WFIntimacyMenuFlags.TargetDead) != 0)
            reasons.Add(Loc.GetString("wf-intimacy-window-dead"));

        if ((menu.Flags & WFIntimacyMenuFlags.TargetUnattended) != 0)
            reasons.Add(Loc.GetString("wf-intimacy-window-unattended"));

        if ((menu.Flags & WFIntimacyMenuFlags.YourMasterConsent) == 0)
            reasons.Add(Loc.GetString("wf-intimacy-window-no-master"));

        if ((menu.Flags & WFIntimacyMenuFlags.YourGivingConsent) == 0)
            reasons.Add(Loc.GetString("wf-intimacy-window-no-giving"));

        StatusLabel.Text = string.Join("\n", reasons);
        StatusLabel.Visible = reasons.Count > 0;

        StopButton.Visible = (menu.Flags & WFIntimacyMenuFlags.SessionOpen) != 0;

        _intensity = menu.Intensity;
        _speed = menu.Speed;

        var intensityId = Array.IndexOf(Intensities, menu.Intensity);
        if (intensityId >= 0)
            IntensityButton.SelectId(intensityId);

        var speedId = Array.IndexOf(Speeds, menu.Speed);
        if (speedId >= 0)
            SpeedButton.SelectId(speedId);

        BuildStats(menu);
        BuildRows(menu);
    }

    /// <summary>Fills the six stat bars from the menu event.</summary>
    private void BuildStats(WFIntimacyMenuEvent menu)
    {
        SetStat(StatsYouArousalBar, StatsYouArousalValue, menu.GiverArousal);
        SetStat(StatsYouPleasureBar, StatsYouPleasureValue, menu.GiverPleasure);
        SetStat(StatsYouWetnessBar, StatsYouWetnessValue, menu.GiverWetness);
        SetStat(StatsTargetArousalBar, StatsTargetArousalValue, menu.ReceiverArousal);
        SetStat(StatsTargetPleasureBar, StatsTargetPleasureValue, menu.ReceiverPleasure);
        SetStat(StatsTargetWetnessBar, StatsTargetWetnessValue, menu.ReceiverWetness);
    }

    private static void SetStat(ProgressBar bar, Label value, byte amount)
    {
        bar.Value = amount;
        value.Text = amount.ToString();
    }

    private void BuildRows(WFIntimacyMenuEvent menu)
    {
        ActList.RemoveAllChildren();

        var section = string.Empty;
        foreach (var entry in menu.Entries)
        {
            var actId = new ProtoId<IntimacyActPrototype>(entry.ActId);
            if (!_proto.TryIndex(actId, out var act))
                continue;

            var kind = KindName(act.Kind);
            if (kind != section)
            {
                section = kind;
                var header = new Label { Text = Loc.GetString(kind) };
                header.StyleClasses.Add("LabelSecondary");
                ActList.AddChild(header);
            }

            var name = Loc.GetString(act.Name);
            var button = new Button
            {
                Text = entry.Failure is { } failure
                    ? Loc.GetString("wf-intimacy-window-row", ("act", name), ("reason", Loc.GetString(failure)))
                    : name,
                Disabled = entry.Failure is not null,
                HorizontalExpand = true,
            };

            button.OnPressed += _ => OnStart?.Invoke(actId, _intensity, _speed);
            ActList.AddChild(button);
        }
    }

    private static string KindName(WFIntimacyKind kind)
    {
        return kind switch
        {
            WFIntimacyKind.Platonic => "wf-intimacy-section-platonic",
            WFIntimacyKind.Oral => "wf-intimacy-section-oral",
            WFIntimacyKind.Penetrative => "wf-intimacy-section-penetrative",
            _ => "wf-intimacy-section-manual",
        };
    }

    private static string IntensityName(WFIntimacyIntensity intensity)
    {
        return intensity switch
        {
            WFIntimacyIntensity.VeryGentle => Loc.GetString("wf-intimacy-intensity-very-gentle"),
            WFIntimacyIntensity.Gentle => Loc.GetString("wf-intimacy-intensity-gentle"),
            WFIntimacyIntensity.Hard => Loc.GetString("wf-intimacy-intensity-hard"),
            WFIntimacyIntensity.Rough => Loc.GetString("wf-intimacy-intensity-rough"),
            _ => Loc.GetString("wf-intimacy-intensity-normal"),
        };
    }

    private static string SpeedName(WFIntimacySpeed speed)
    {
        return speed switch
        {
            WFIntimacySpeed.Slow => Loc.GetString("wf-intimacy-speed-slow"),
            WFIntimacySpeed.Fast => Loc.GetString("wf-intimacy-speed-fast"),
            _ => Loc.GetString("wf-intimacy-speed-normal"),
        };
    }
}